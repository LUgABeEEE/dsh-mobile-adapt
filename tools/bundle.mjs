#!/usr/bin/env node
/**
 * dsh-adapt-packs · bundle
 *
 * 把仓库里的多张适配包合成**一个**可安装的 dsh-mobile 扩展，供 dsh-mobile 只选装这一份插件。
 *
 * 设计：
 *   - 源仍然是 packs/<id>/（每张包独立可装、可测，check-pack 照常跑）；
 *   - 输出 build/<id>/ 是**生成物**（gitignored），不参与 check-pack；
 *   - 扩展 id 固定，extension.json 只有 5 个字段；
 *   - mobile.css 按固定顺序拼接；mobile.js 拦截各包的 define()，最后只 define 一次，
 *     把各包的 activate 组合起来并统一返回清理函数。
 *
 * 用法：
 *   node tools/bundle.mjs [--out <dir>] [--dry-run]
 *
 * 默认输出 build/dsh-ui-optimizer/；安装用
 *   node tools/install.mjs pack dsh-ui-optimizer --from build/dsh-ui-optimizer --yes
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PLUGIN_ID = 'dsh-ui-optimizer'
const PLUGIN_NAME = 'DSH Mobile UI Optimizer'
const SOURCES = [
  { id: 'core-panel', note: '面板内的触控地板、宽度收口与滚动约束（宿主已接管时自动退让）' },
  { id: 'shell-chrome', note: '外壳自身的触控下限（返回栏只抬不压，抽屉行 44px）' },
  { id: 'floaters', note: '右下角浮动控件的让位（实测占用高度，写成 --dshm-floaters）' },
  { id: 'dshmarket-mobile', note: '插件市场面板（dshmarket 1.73.x）的触控地板' },
  { id: 'host-service-panel-mobile', note: 'host-service 面板的手机布局与触控地板' },
]

function read(relative) {
  const path = join(ROOT, relative)
  if (!existsSync(path)) throw new Error(`缺少源文件：${relative}`)
  return readFileSync(path, 'utf8')
}

function readOptional(relative) {
  const path = join(ROOT, relative)
  return existsSync(path) ? readFileSync(path, 'utf8') : ''
}

function parseOut(argv) {
  let out = join(ROOT, 'build', PLUGIN_ID)
  let dryRun = false
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]
    if (argument === '--dry-run') dryRun = true
    else if (argument === '--out') {
      index += 1
      if (argv[index] === undefined) throw new Error('--out 需要一个目录')
      out = resolve(argv[index])
    } else if (argument === '--help' || argument === '-h') {
      console.log('用法：node tools/bundle.mjs [--out <dir>] [--dry-run]')
      process.exit(0)
    } else throw new Error(`未知参数：${argument}`)
  }
  return { out, dryRun }
}

function banner(title) {
  return `/*! ${title} — generated by tools/bundle.mjs; edit packs/${title}/ instead */\n`
}

function buildCss() {
  const parts = SOURCES.map(source => `${banner(source.id)}${read(`packs/${source.id}/mobile.css`).trimEnd()}\n`)
  return `${banner(PLUGIN_ID)}\n/* 由 packages 合成：${SOURCES.map(source => source.id).join(' + ')} */\n\n${parts.join('\n')}`
}

function buildJs() {
  const blocks = SOURCES.flatMap(source => {
    const script = readOptional(`packs/${source.id}/mobile.js`)
    if (script.trim() === '') return []
    const rewritten = script.replaceAll('window.dshMobile.define(', 'window.__dshAdaptCollect(')
    if (rewritten === script) throw new Error(`packs/${source.id}/mobile.js 里找不到 window.dshMobile.define(，无法收集定义`)
    if (rewritten.includes('dshMobile.define(')) throw new Error(`packs/${source.id}/mobile.js 还有别的 define 调用，打包会漏定义`)
    const indented = rewritten.trimEnd().split('\n').map(line => `  ${line}`).join('\n')
    return [`  // ---- packs/${source.id}/mobile.js ----\n  {\n${indented}\n  }\n`]
  })
  return `${banner(PLUGIN_ID)}
/*
 * 由 tools/bundle.mjs 生成：把各源包里 define() 的那一份定义收集起来，
 * 最后只向宿主注册一个扩展。源包在单独安装时仍然自己调用 define()。
 */
(function () {
  'use strict'
  if (typeof window.dshMobile === 'undefined' || typeof window.dshMobile.define !== 'function') return
  var definitions = []
  window.__dshAdaptCollect = function (definition) { definitions.push(definition) }
  try {
${blocks.join('\n')}  } finally {
    delete window.__dshAdaptCollect
  }
  window.dshMobile.define({
    apiVersion: 1,
    id: ${JSON.stringify(PLUGIN_ID)},
    activate: function (api) {
      var cleanups = []
      for (var index = 0; index < definitions.length; index += 1) {
        var definition = definitions[index]
        if (definition === null || typeof definition !== 'object' || typeof definition.activate !== 'function') continue
        var cleanup = definition.activate(api)
        if (typeof cleanup === 'function') cleanups.push(cleanup)
      }
      return function () {
        for (var position = cleanups.length - 1; position >= 0; position -= 1) {
          try { cleanups[position]() } catch (error) {}
        }
      }
    },
  })
})()
`
}

function buildReadme(version) {
  const lines = [
    `# ${PLUGIN_NAME}`,
    '',
    '> 生成物，不要直接编辑；源在 `packs/`，用 `node tools/bundle.mjs` 重新生成。',
    '',
    `版本：${version}`,
    '',
    '这个扩展把本仓库的 UI 优化规则合成**一份**插件，dsh-mobile 只需要选装它：',
    '',
    ...SOURCES.map(source => `- \`${source.id}\`：${source.note}`),
    '',
    '## 安装 / 卸载',
    '',
    '```bash',
    'node tools/bundle.mjs',
    'node tools/install.mjs pack dsh-ui-optimizer --from build/dsh-ui-optimizer --yes',
    'node tools/install.mjs --uninstall dsh-ui-optimizer --yes',
    '```',
    '',
    '## 关闭',
    '',
    '- 整体：外壳根节点或主槽子树加 `data-dsh-adapt="off"`；',
    '- 面板规则另有宿主门阀：宿主自己写 `data-dsh-panel` 时（dsh-mobile #319 起），本插件的触控地板与宽度收口自动退让。',
    '',
    '真机、软键盘与 `env(safe-area-inset-*)` 仍未验证；默认按「可回退」设计：删掉扩展目录即恢复。',
  ]
  return `${lines.join('\n')}\n`
}

function main() {
  const { out, dryRun } = parseOut(process.argv.slice(2))
  const pkg = JSON.parse(read('package.json'))
  const extension = {
    schemaVersion: 1,
    id: PLUGIN_ID,
    name: PLUGIN_NAME,
    version: pkg.version,
    description: '把 dsh-adapt-packs 的移动端 UI 优化规则合成一份可选插件：面板触控地板、外壳触控下限与浮动控件让位；可整页 opt-out。',
  }
  const files = {
    'extension.json': `${JSON.stringify(extension, null, 2)}\n`,
    'mobile.css': buildCss(),
    'mobile.js': buildJs(),
    'README.md': buildReadme(pkg.version),
  }
  const summary = Object.entries(files).map(([name, body]) => `${name} (${Buffer.byteLength(body)} B)`)
  if (dryRun) {
    console.log(`dry-run：将写入 ${out}`)
    for (const line of summary) console.log(`  ${line}`)
    return
  }
  rmSync(out, { recursive: true, force: true })
  mkdirSync(out, { recursive: true })
  for (const [name, body] of Object.entries(files)) writeFileSync(join(out, name), body, 'utf8')
  console.log(`built ${out}`)
  for (const line of summary) console.log(`  ${line}`)
}

main()
